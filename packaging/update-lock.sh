#!/bin/sh
# Regenerate requirements.txt: the pinned, hashed runtime dependencies the
# standalone build installs. Run after changing dependencies in
# pyproject.toml, then commit the result.
#
#   packaging/update-lock.sh
#
# PYTHON_VERSION and GLIBC must match what build-standalone.sh uses.
set -eu

PYTHON_VERSION=${PYTHON_VERSION:-3.12}
GLIBC=${GLIBC:-2.28}
ARCH=${ARCH:-$(uname -m)}

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
command -v uv >/dev/null 2>&1 || {
    echo "uv is required: https://docs.astral.sh/uv/" >&2
    exit 1
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
uv pip compile "$root/pyproject.toml" \
    --python-version "$PYTHON_VERSION" \
    --python-platform "${ARCH}-manylinux_$(echo "$GLIBC" | tr . _)" \
    --generate-hashes --no-header --quiet -o "$tmp"

{
    echo "# Pinned, hashed runtime dependencies for the standalone build."
    echo "# Generated by packaging/update-lock.sh -- do not edit by hand."
    echo "# Python $PYTHON_VERSION, ${ARCH}, glibc >= $GLIBC"
    cat "$tmp"
} > "$root/requirements.txt"
echo "wrote $root/requirements.txt"
